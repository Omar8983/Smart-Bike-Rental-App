-- Drop existing tables (child tables first) so the script can be re-run
-- on a development database. WARNING: this deletes existing data.
DROP TABLE IF EXISTS damage_reports;
DROP TABLE IF EXISTS rentals;
DROP TABLE IF EXISTS bikes;
DROP TABLE IF EXISTS pricing_plans;
DROP TABLE IF EXISTS stations;
DROP TABLE IF EXISTS users;

-- ---------------------------------------------------------------------
-- 1. users: riders, admins, and company (fleet operator) accounts
-- ---------------------------------------------------------------------
CREATE TABLE users (
    user_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      VARCHAR(100) NOT NULL,
    email          VARCHAR(255) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    role           VARCHAR(20)  NOT NULL DEFAULT 'rider'
                   CHECK (role IN ('rider', 'admin', 'company')),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- 2. stations: docking stations where bikes are picked up / returned
-- ---------------------------------------------------------------------
CREATE TABLE stations (
    station_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL UNIQUE,
    location        VARCHAR(255) NOT NULL,
    capacity        INTEGER      NOT NULL CHECK (capacity > 0),
    operating_info  VARCHAR(255),
    is_active       BOOLEAN      NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------------------
-- 3. pricing_plans: hourly / daily / weekly plans
-- ---------------------------------------------------------------------
CREATE TABLE pricing_plans (
    pricing_plan_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(50)   NOT NULL UNIQUE,
    duration         INTERVAL      NOT NULL CHECK (duration > INTERVAL '0'),
    price            NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    is_active        BOOLEAN       NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------------------
-- 4. bikes: each physical bike, identified by a unique QR code
-- ---------------------------------------------------------------------
CREATE TABLE bikes (
    bike_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- NULL while the bike is out on a rental (not docked at any station).
    -- ON DELETE RESTRICT: a station that still has bikes cannot be deleted;
    -- move the bikes first or set stations.is_active = FALSE instead.
    station_id  INTEGER REFERENCES stations (station_id) ON DELETE RESTRICT,
    qr_code     VARCHAR(50) NOT NULL UNIQUE,
    status      VARCHAR(20) NOT NULL DEFAULT 'available'
                CHECK (status IN ('available', 'rented', 'maintenance')),
    -- A rented bike is with the rider, so it cannot be docked at a station.
    CHECK (status <> 'rented' OR station_id IS NULL)
);

-- ---------------------------------------------------------------------
-- 5. rentals: one row per bike rental (active, completed, or cancelled)
-- ---------------------------------------------------------------------
CREATE TABLE rentals (
    rental_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- ON DELETE RESTRICT: keep rental/billing history; users with rentals
    -- cannot be deleted.
    user_id           INTEGER NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    -- ON DELETE RESTRICT: keep rental history; bikes with rentals cannot be deleted.
    bike_id           INTEGER NOT NULL REFERENCES bikes (bike_id) ON DELETE RESTRICT,
    -- ON DELETE RESTRICT: keep trip history; deactivate the station instead.
    start_station_id  INTEGER NOT NULL REFERENCES stations (station_id) ON DELETE RESTRICT,
    -- NULL while the rental is active (bike not returned yet).
    -- ON DELETE RESTRICT: keep trip history; deactivate the station instead.
    end_station_id    INTEGER REFERENCES stations (station_id) ON DELETE RESTRICT,
    -- ON DELETE RESTRICT: past rentals must keep their plan; set
    -- pricing_plans.is_active = FALSE to retire a plan.
    pricing_plan_id   INTEGER NOT NULL REFERENCES pricing_plans (pricing_plan_id) ON DELETE RESTRICT,
    start_time        TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    end_time          TIMESTAMPTZ,
    status            VARCHAR(20)   NOT NULL DEFAULT 'active'
                      CHECK (status IN ('active', 'completed', 'cancelled')),
    total_cost        NUMERIC(10,2) CHECK (total_cost >= 0),

    CHECK (end_time IS NULL OR end_time > start_time),
    -- Rental lifecycle:
    --   active    -> not returned yet: no end time, end station, or cost
    --   completed -> returned: end time, end station, and cost are required
    CHECK (status <> 'active'
           OR (end_time IS NULL AND end_station_id IS NULL AND total_cost IS NULL)),
    CHECK (status <> 'completed'
           OR (end_time IS NOT NULL AND end_station_id IS NOT NULL AND total_cost IS NOT NULL))
);

-- A bike can be part of at most one active rental at a time.
CREATE UNIQUE INDEX uq_rentals_one_active_per_bike
    ON rentals (bike_id)
    WHERE status = 'active';

-- ---------------------------------------------------------------------
-- 6. damage_reports: issues reported by users about a bike
-- ---------------------------------------------------------------------
CREATE TABLE damage_reports (
    report_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- ON DELETE CASCADE: a report only describes one bike; if that bike
    -- record is removed, its reports are removed with it.
    bike_id      INTEGER NOT NULL REFERENCES bikes (bike_id) ON DELETE CASCADE,
    -- ON DELETE RESTRICT: keep who reported the issue; users with
    -- reports cannot be deleted.
    user_id      INTEGER NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    issue_type   VARCHAR(30) NOT NULL
                 CHECK (issue_type IN ('brakes', 'tires', 'chain', 'lights', 'frame', 'other')),
    description  TEXT        NOT NULL,
    status       VARCHAR(20) NOT NULL DEFAULT 'open'
                 CHECK (status IN ('open', 'in_progress', 'resolved')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
